"""A8 - the fitted response surface: health state -> 21 sensor readings.

THIS IS THE FITTED HALF OF THE REPLICATION, and it is deliberately kept in its
own module so the boundary with damage.py (which is exact, from published
equations) stays visible and auditable.

WHY IT HAS TO BE FITTED
    The paper's Figure 4 shows a response surface mapping efficiency and flow
    loss to a sensor value, generated by the C-MAPSS thermodynamic model. That
    model was never publicly released, so the surfaces cannot be reproduced from
    first principles. They are instead recovered from the released data.

FIT ON TRAIN UNITS ONLY
    Every coefficient here is estimated from train_FDxxx.txt. The test split is
    never touched, so the TSTR gate (A17) - train a model on our synthetic data,
    evaluate it on NASA's real test set - remains an honest held-out comparison.

FUNCTIONAL FORM, CHOSEN FROM THE DATA NOT ASSUMED
    Regressing each informative FD001 sensor on normalised life shows quadratic
    consistently beating linear (e.g. T50 R^2 0.506 -> 0.606, Ps30 0.529 ->
    0.633) while cubic adds almost nothing (0.617, 0.645). So the mean trend is
    quadratic in health. Measured, recorded, and re-measured per subset rather
    than hardcoded.

NOISE DECOMPOSITION FEEDS A9
    In FD001 the within-unit standard deviation is 0.79-0.99 of the total for
    every sensor, i.e. C-MAPSS is noise-dominated and the degradation trend is a
    minority of the variance. We split the residual into a between-unit
    component (one offset per unit - manufacturing variation and the process
    noise that the paper filters through the engine model) and a within-unit
    component (per-cycle measurement noise). A9 reproduces both, in that order,
    which is the order the paper specifies.
"""
from __future__ import annotations

